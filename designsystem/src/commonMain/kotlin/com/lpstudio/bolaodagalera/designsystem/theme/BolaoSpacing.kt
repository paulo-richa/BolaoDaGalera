package com.lpstudio.bolaodagalera.designsystem.theme

import androidx.compose.ui.unit.dp

/**
 * App spacing scale (4dp grid, even numbers only). Not an official
 * Material 3 token - M3 does not prescribe spacing - but it is a recommended
 * practice in Google's reference apps (Now in Android, Jetsnack, Reply) to
 * avoid magic `.dp` values scattered across screens.
 */
object BolaoSpacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 20.dp
    val xxl = 24.dp
    val xxxl = 32.dp
    val huge = 40.dp
}
